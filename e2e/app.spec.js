test('초안 복원, 선택 확정, 새로운 고민을 시작한다', async ({ page }) => {
 await page.goto('/');
 await page.getByLabel('고민의 제목').fill('주말 계획');
 await page.getByLabel('선택지 1', { exact: true }).fill('산책');
 await page.getByLabel('선택지 2', { exact: true }).fill('영화');
 await page.reload();
 await expect(page.getByLabel('고민의 제목')).toHaveValue('주말 계획');
 await expect(page.getByLabel('선택지 1', { exact: true })).toHaveValue('산책');
 await page.getByRole('button', { name: '하나 골라줘', exact: true }).click();
 await page.keyboard.press('Shift+Tab');
 await expect(page.getByRole('button', { name: '한 번 더 골라보기' })).toBeFocused();
 await page.keyboard.press('Tab');
 await expect(page.getByRole('button', { name: '결과 닫기' })).toBeFocused();
 await page.getByRole('button', { name: '좋아, 이걸로 할래' }).click();
 await expect(page.locator('.accepted strong')).toHaveText(/^(산책|영화)$/);
 await expect(page.getByRole('button', { name: '하나 골라줘', exact: true })).toBeFocused();
 await page.getByRole('button', { name: '새로운 고민 시작하기' }).click();
 await expect(page.getByLabel('고민의 제목')).toBeEmpty();
 await expect(page.getByLabel('고민의 제목')).toBeFocused();
 await expect(page.getByLabel('선택지 1', { exact: true })).toBeEmpty();
});
