test('개인정보 안내에서 초안과 기록을 함께 삭제한다', async ({ page }) => {
 await page.goto('/');
 await page.getByLabel('선택지 1', { exact: true }).fill('파스타');
 await page.getByLabel('선택지 2', { exact: true }).fill('초밥');
 await page.getByRole('button', { name: '하나 골라줘', exact: true }).click();
 await page.getByRole('button', { name: '좋아, 이걸로 할래' }).click();
 await page.getByRole('button', { name: '앱·개인정보 안내' }).click();
 await expect(page.getByRole('heading', { name: '무엇을 저장하나요?' })).toBeVisible();
 page.on('dialog', dialog => dialog.accept());
 await page.getByRole('button', { name: '선택지와 기록 모두 지우기' }).click();
 await expect(page.getByRole('status')).toContainText('삭제했어요');
 await page.reload();
 await expect(page.getByLabel('선택지 1', { exact: true })).toBeEmpty();
 await page.getByRole('button', { name: '내 선택 기록', exact: true }).click();
 await expect(page.getByText('아직 선택 기록이 없어요.')).toBeVisible();
});
