import { test, expect } from '@playwright/test';
test('선택, 기록 저장 및 삭제가 동작한다', async ({ page }) => {
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button', { name: '하나 골라줘', exact: true }).click();
 await expect(page.getByRole('alert')).toContainText('두 개 이상');
 await page.getByLabel('선택지 1', { exact: true }).fill('파스타');
 await page.getByLabel('선택지 2', { exact: true }).fill('초밥');
 await page.getByRole('button', { name: '하나 골라줘', exact: true }).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.locator('#result-title')).toHaveText(/^(파스타|초밥)$/);
 await page.getByRole('button', { name: '좋아, 이걸로 할래' }).click();
 await page.reload();
 await page.getByRole('button', { name: '내 선택 기록', exact: true }).click();
 await expect(page.locator('.history-item')).toHaveCount(1);
 page.on('dialog', dialog => dialog.accept());
 await page.getByRole('button', { name: '기록 모두 지우기' }).click();
 await expect(page.getByText('아직 선택 기록이 없어요.')).toBeVisible();
 expect(errors).toEqual([]);
});
